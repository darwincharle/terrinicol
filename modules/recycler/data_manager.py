def filter_data(df, search_term, groups, countries, uses, density_range):
    # Aplicar todos los filtros
    filtered = df.copy()
    
    if search_term:
        filtered = filtered[
            filtered['nombre'].str.contains(search_term, case=False) |
            filtered['simbolo'].str.contains(search_term, case=False)
        ]
    
    if groups:
        filtered = filtered[filtered['grupo'].isin(groups)]
    
    if countries:
        filtered = filtered[filtered['pais'].isin(countries)]
    
    if uses:
        filtered = filtered[filtered['usos'].apply(lambda x: any(use in x for use in uses))]
    
    filtered = filtered[
        (filtered['densidad'] >= density_range[0]) &
        (filtered['densidad'] <= density_range[1])
    ]
    
    return filtered